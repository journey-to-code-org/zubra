// In production the component modules are minified by the compiler (`command: "minify"`), the
// CSS in them too; in development, with the DevTools, or with `minify: false`, they go as the
// compiler writes them.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { gzipSync } from 'node:zlib';
import { dirname, join } from 'node:path';
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import * as compiler from '@zubra/compiler';
import { createZubra } from '../src/index.js';
import { createZubra as createEdge } from '../src/edge.js';

const here = dirname(fileURLToPath(import.meta.url));
const components = join(here, 'components');
const layout = (body) => `<!doctype html><html><head><meta charset="utf-8"><title>t</title></head><body>${body}</body></html>`;
const get = (zubra, url) => {
  const answer = { status: 404, body: '' };
  zubra.handle({ url }, { writeHead: (status) => (answer.status = status), end: (body) => (answer.body = String(body)) });
  return answer;
};

test('in production a component module is minified, its CSS too, and smaller', () => {
  const minified = get(createZubra({ components, production: true }), '/_zubra/components/count-stepper.js');
  const plain = get(createZubra({ components, production: true, minify: false }), '/_zubra/components/count-stepper.js');
  assert.equal(minified.status, 200);
  assert.doesNotMatch(minified.body, /Generated by zubra/);
  assert.match(plain.body, /Generated by zubra/);
  // The CSS: `output { font-weight: 700; }` in the source.
  assert.match(minified.body, /output\{font-weight: 700\}/);
  assert.match(plain.body, /output \{ font-weight: 700; \}/);
  // What the server changed before minifying is kept: each name from the file that has it.
  assert.match(minified.body, /from"\.\.\/runtime\/form\.js"/);
  assert.ok(gzipSync(minified.body).length < gzipSync(plain.body).length);
  assert.ok(minified.body.length < plain.body.length * 0.8, `${minified.body.length} of ${plain.body.length}`);
});

test('development, the DevTools and minify: false send the module as the compiler writes it', () => {
  for (const options of [{ production: false }, { production: true, devtools: true }, { production: true, minify: false }]) {
    const body = get(createZubra({ components, ...options }), '/_zubra/components/count-stepper.js').body;
    assert.match(body, /Generated by zubra/, JSON.stringify(options));
  }
});

test('bundle: the joined module is minified once, after joining, and is still one module', () => {
  const zubra = createZubra({ components, production: true, bundle: true });
  const page = zubra.page();
  page.render('order-form', {});
  const html = page.finish(layout(''));
  const url = html.match(/\/_zubra\/b\/count-stepper\+order-form\.[\w]+\.js/)?.[0];
  assert.ok(url, 'the page names one joined module');
  const body = get(zubra, url).body;
  assert.doesNotMatch(body, /Generated by zubra/);
  assert.match(body, /`count-stepper`/);
  assert.match(body, /`order-form`/);
});

test('a compiler without the minify command: the module goes as it is', async () => {
  const older = { ...compiler, request: (body) => (body.command === 'minify' ? { ok: false, error: 'unknown command `minify`' } : compiler.request(body)) };
  const source = readFileSync(join(components, 'count-stepper.zb'), 'utf8');
  const zubra = createEdge({ compiler: older, components: { 'count-stepper': source } });
  const fetched = async (edge) => (await edge.fetch(new Request('http://localhost/_zubra/components/count-stepper.js'))).text();
  assert.match(await fetched(zubra), /Generated by zubra/);
  const current = createEdge({ compiler, components: { 'count-stepper': source } });
  assert.doesNotMatch(await fetched(current), /Generated by zubra/);
});
