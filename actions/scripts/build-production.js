// The production build of @zubra/actions' browser scripts (`dist/production/`): the same modules,
// minified, each on its own (esbuild, pinned in devDependencies, so the output is the same
// everywhere): one module per file, imported as before, but without comments and long names.
// `src/` is the code to read; this is what `createActions` serves in production, where it halves
// the bytes, as the runtime's and @zubra/sync's production builds do. `--check` fails if the build is out of date.
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { transformSync } from 'esbuild';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const from = join(root, 'src');
const to = join(root, 'dist/production');
const check = process.argv.includes('--check');

/** What a page loads: the script for action forms, and the one for plain forms that name what they update. */
export const BROWSER = ['client.js', 'enhance-forms.js'];

/** A module, minified, under a header that points back to its source. */
export function minified(source, file) {
  const { code } = transformSync(source, {
    minify: true,
    format: 'esm',
    target: 'esnext', // minify only: no syntax rewritten
    legalComments: 'none',
    sourcefile: `src/${file}`,
  });
  return `// Generated by scripts/build-production.js from src/${file}. Minified; read src/ instead. Do not edit.\n${code}`;
}

const stale = [];
if (!check) mkdirSync(to, { recursive: true });
for (const file of BROWSER) {
  const built = minified(readFileSync(join(from, file), 'utf8'), file);
  const target = join(to, file);
  if (check) {
    if (!existsSync(target) || readFileSync(target, 'utf8') !== built) stale.push(file);
  } else {
    writeFileSync(target, built);
  }
}
if (stale.length) {
  console.error(`dist/production is out of date (${stale.join(', ')}): run npm run build in actions/`);
  process.exit(1);
}
