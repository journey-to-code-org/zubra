// The production build of the runtime (`dist/production/`, the `production` export condition):
// the same modules, without what only development uses, and minified. Code between `// @hot` and
// `// @hot-end` (hot reloading) or `// @dev` and `// @dev-end` (the DevTools hook) is left out,
// `globalThis.__ZUBRA_HOT__` reads as false, and each file is minified on its own (esbuild, pinned
// in devDependencies, so the output is the same everywhere): still one module per file, imported as
// before, but without comments and long names. `src/` is the runtime to read; this is the one a
// server without a bundler sends (`@zubra/server` in production), where it halves the bytes.
// `--check` fails if the build is out of date.
import { readdirSync, readFileSync, writeFileSync, mkdirSync, mkdtempSync, rmSync, existsSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { buildSync, transformSync } from 'esbuild';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const from = join(root, 'src');
const to = join(root, 'dist/production');
const check = process.argv.includes('--check');
// Modules only development imports (from `// @dev` blocks): not in the production build at all.
const DEV_ONLY = ['devhook.js', 'devtools.js', 'mismatch.js'];

// Fields of objects that never leave their module, by module: the production build gives them
// short names (esbuild's `mangleProps`), where minifying alone keeps every property's name. A
// name belongs here only if, in that file, it is read and written on those objects alone: the
// signal graph's nodes (`Node`; `equals` is also an option's name, so it stays), and an effect's
// owner (`Owner`, `Effect`; `disposed`, `paused`, `dispose`, `run`, `pause` and `resume` are its public
// side). `private.test.js` checks each name's every use in `src/`.
export const PRIVATE = {
  'signal-impl.js': ['kind', 'wrapper', 'version', 'dirty', 'value', 'error', 'computation', 'notify', 'onWatched', 'onUnwatched', 'lastCleanEpoch', 'sinks', 'sinkSlots', 'sources', 'sourceVersions', 'sourceSlots', 'nextSource', 'pending', 'seen'],
  'signal-core.js': ['kind', 'wrapper', 'version', 'dirty', 'value', 'error', 'computation', 'lastCleanEpoch', 'sinks', 'sinkSlots', 'sources', 'sourceVersions', 'sourceSlots', 'nextSource', 'group', 'live', 'seen'],
  'effect.js': ['parent', 'children', 'cleanup', 'computed', 'runCleanup', 'disposeChildren'],
};

export function production(source, file = 'module') {
  const lines = source.split('\n');
  const out = [];
  let depth = 0;
  for (const [index, line] of lines.entries()) {
    const marker = line.trim();
    if (marker.startsWith('// @hot-end') || marker.startsWith('// @dev-end')) {
      if (!depth--) throw new Error(`${file}:${index + 1}: ${marker.slice(3, 11)} without its start`);
      continue;
    }
    if (marker.startsWith('// @hot') || marker.startsWith('// @dev')) {
      depth++;
      continue;
    }
    if (!depth) out.push(line);
  }
  if (depth) throw new Error(`${file}: @hot or @dev without its end`);
  const code = out.join('\n').replaceAll('globalThis.__ZUBRA_HOT__', 'false');
  return `// Generated by scripts/build-production.js from src/${file}: the runtime without hot reloading or the DevTools hook. Do not edit.\n${code}`;
}

/** `production()`'s module, minified, under the same header (a pointer back to its source). */
export function minified(source, file = 'module') {
  const stripped = production(source, file);
  const header = stripped.slice(0, stripped.indexOf('\n') + 1);
  const { code } = transformSync(stripped.slice(header.length), {
    minify: true,
    format: 'esm',
    target: 'esnext', // minify only: no syntax rewritten
    legalComments: 'none',
    sourcefile: `src/${file}`,
    ...(PRIVATE[file] ? { mangleProps: new RegExp(`^(?:${PRIVATE[file].join('|')})$`) } : {}),
  });
  return `${header.replace('Do not edit.', 'Minified; read src/ instead. Do not edit.')}${code}`;
}

/**
 * `dist/modules.js` (`@zubra/runtime/modules`): for each module of the production build, the
 * modules it imports statically. A server that sends the runtime file by file reads it to tell
 * the browser every module a page needs at once (`<link rel="modulepreload">`), including where
 * it can't read the files itself (`@zubra/server/edge`). Every module named here is in the
 * development build too, so the list is safe whichever build is served.
 */
export function moduleGraph(sources, bundledSources, splitSources) {
  const split = !splitSources ? '' : `\n// The names core.js has that base.js doesn't, and the file each is in: what a server sends only to\n// the pages whose components import it (\`@zubra/server\` takes each from its file).\nexport const split = ${JSON.stringify({ ...splitNames(sources), modules: graphOf(splitSources) }, null, 2)};\n`;
  const bundled = bundledSources ? `\n// The same for dist/bundled, where the entry and what it imports are one file (zubra.js).\nexport const bundled = ${JSON.stringify(graphOf(bundledSources), null, 2)};\n` : '';
  return `// Generated by scripts/build-production.js from dist/production: each module's static imports. Do not edit.\nexport default ${JSON.stringify(graphOf(sources), null, 2)};\n${bundled}${split}`;
}

/** The base's file, and for each name `core.js` exports from another module, that module's file. */
export function splitNames(sources, CORE = 'core.js', BASE = 'base.js') {
  const names = {};
  for (const [, list, from] of sources[CORE].matchAll(/(?:import|export)\s*\{([^}]*)\}\s*from\s*["']\.\/([^"']+)["']/g)) {
    if (from !== BASE && from !== BUNDLE) for (const one of list.split(',')) if (one.trim()) names[one.trim().split(/\s+as\s+/)[0]] = from;
  }
  return { base: BASE, names: Object.fromEntries(Object.entries(names).sort(([a], [b]) => (a < b ? -1 : 1))) };
}

/** Each module's static imports, by file name. */
export function graphOf(sources) {
  const graph = {};
  for (const name of Object.keys(sources).sort()) {
    const found = [];
    // `import"./x.js"` and `from"./x.js"`; `import("./x.js")` loads when it runs, so isn't one.
    for (const match of sources[name].matchAll(/(?:\bfrom|\bimport)\s*["']\.\/([^"']+)["']/g)) if (!found.includes(match[1])) found.push(match[1]);
    graph[name] = found;
  }
  return graph;
}

/** The file the entry and everything it imports become in `dist/bundled`. */
export const BUNDLE = 'zubra.js';

/**
 * `dist/bundled`: the production build with the entry (`index.js`) and every module it imports
 * as one file, `zubra.js`, for a server that sends the runtime to a browser without a bundler
 * (`@zubra/server` with `bundle`): one request where there were seven, and about a seventh
 * fewer bytes, since the modules compress together. The other modules (`spread.js`, `track.js`,
 * …) are the production ones with their imports of those modules pointed at `zubra.js`, so there
 * is one copy of the signal graph whichever of them a page loads; and each module that went into
 * `zubra.js` is still there by name, re-exporting from it, for anything that imports it directly.
 * `zubra.js` exports what the entry (`core.js`) does and what those others need from inside; what
 * `index.js` adds to the core (`$define` and `$element` from `legacy.js`, `$await`, the slots) stays in
 * those modules' own files.
 *
 * `dist/split` is the same made from `base.js` (`bundle(sources, 'base.js')`): there `zubra.js` is
 * the base alone, and context, form controls, event modifiers, shadow roots and `resource()` are
 * files beside it, for a server that sends each to the pages that use it. `dist/bundled` stays as
 * it is, whole, for a server from before the split (which takes every one of those names from
 * `zubra.js`).
 */
export function bundle(sources, ENTRY = 'core.js') {
  const graph = graphOf(sources);
  const core = [];
  (function walk(name) {
    if (core.includes(name)) return;
    core.push(name);
    for (const next of graph[name] ?? []) walk(next);
  })(ENTRY);
  const dir = mkdtempSync(join(tmpdir(), 'zubra-bundled-'));
  try {
    for (const [name, code] of Object.entries(sources)) writeFileSync(join(dir, name), code);
    const namedBy = (name) => Object.values(buildSync({ entryPoints: [join(dir, name)], bundle: false, write: false, metafile: true, format: 'esm', outdir: join(dir, 'out') }).metafile.outputs)[0].exports;
    // (With what it takes whole from another module: `export * from './base.js'`.)
    const exportsOf = (name) => [...new Set([...namedBy(name), ...[...sources[name].matchAll(/export\s*\*\s*from\s*["']\.\/([^"']+)["']/g)].flatMap((match) => exportsOf(match[1]))])].sort();
    const entry = exportsOf(ENTRY);
    // What each module adds to the entry's exports: the names only it has. A name two of them
    // export (`Signal`: the one chosen, and the implementation) is the entry's, or nobody's.
    const owned = Object.fromEntries(core.filter((name) => name !== ENTRY).map((name) => [name, exportsOf(name)]));
    const count = (name) => Object.values(owned).filter((names) => names.includes(name)).length;
    const extra = Object.fromEntries(Object.entries(owned).map(([name, names]) => [name, names.filter((one) => !entry.includes(one) && count(one) === 1)]));
    const stdin = [`export * from './${ENTRY}';`, ...Object.entries(extra).filter(([, names]) => names.length).map(([name, names]) => `export { ${names.join(', ')} } from './${name}';`)].join('\n');
    // A module loaded when it's first needed (`import('./remark.js')`) stays a file of its own.
    const lazy = [...new Set(core.flatMap((name) => [...sources[name].matchAll(/\bimport\(\s*["'](\.\/[^"']+)["']\s*\)/g)].map((match) => match[1])))];
    const { outputFiles } = buildSync({ stdin: { contents: stdin, resolveDir: dir, sourcefile: 'zubra.js' }, bundle: true, minify: true, format: 'esm', target: 'esnext', legalComments: 'none', external: lazy, write: false });
    const header = (what) => `// Generated by scripts/build-production.js: ${what} Minified; read src/ instead. Do not edit.\n`;
    const out = { [BUNDLE]: `${header(`${core.join(', ')} as one module.`)}${outputFiles[0].text}` };
    // Where the entry gets each of its names: a name two modules export is that module's.
    const origin = {};
    // (The entry only re-exports, under the names it imports; minified, that is `import{a as b}from`.)
    // (And what it takes whole from another module, `export * from './base.js'`, is that module's
    // to say.)
    const entryCode = [sources[ENTRY], ...[...sources[ENTRY].matchAll(/export\s*\*\s*from\s*["']\.\/([^"']+)["']/g)].map((match) => sources[match[1]])].join('\n');
    for (const [, names, from] of entryCode.matchAll(/(?:import|export)\s*\{([^}]*)\}\s*from\s*["']\.\/([^"']+)["']/g)) for (const one of names.split(',')) origin[one.trim().split(/\s+as\s+/)[0]] = from;
    for (const one of entry) if (!origin[one]) throw new Error(`${ENTRY} exports ${one}, and not from a module by that name`);
    const gives = { [ENTRY]: entry };
    for (const name of Object.keys(owned)) gives[name] = owned[name].filter((one) => extra[name].includes(one) || origin[one] === name);
    for (const name of core) {
      // A module with nothing that is its own to give (the signal implementation: `Signal` is
      // signal.js's, which chooses) has no file; nothing outside `zubra.js` imports it.
      if (gives[name].length) out[name] = `${header(`${name}'s exports, from ${BUNDLE}.`)}export{${gives[name].join(',')}}from"./${BUNDLE}";\n`;
    }
    const inside = new RegExp(`((?:\\bfrom|\\bimport)\\s*["'])\\./(${core.map((name) => name.replace(/[.$]/g, '\\$&')).join('|')})(["'])`, 'g');
    const named = new RegExp(`import\\s*\\{([^}]*)\\}\\s*from\\s*["']\\./(${core.map((name) => name.replace(/[.$]/g, '\\$&')).join('|')})["']`, 'g');
    for (let [name, code] of Object.entries(sources)) {
      if (core.includes(name)) continue;
      // `export * from './core.js'` (index.js): the core's own names, from `zubra.js`, and not the
      // internals other modules of it give there too.
      code = code.replace(new RegExp(`export\\s*\\*\\s*from\\s*["']\\./${ENTRY.replace('.', '\\.')}["'];?`, 'g'), `export{${entry.join(',')}}from"./${BUNDLE}";`);
      // Every name it takes from a module inside `zubra.js` must be one that module gives there.
      let imports = 0;
      for (const [, names, from] of code.matchAll(named)) {
        imports++;
        for (const one of names.split(',').map((one) => one.trim().split(/\s+as\s+/)[0]).filter(Boolean)) {
          if (!gives[from].includes(one)) throw new Error(`${name} imports ${one} from ${from}, which ${BUNDLE} doesn't export as that module's`);
        }
      }
      if ([...code.matchAll(inside)].length !== imports) throw new Error(`${name} imports a module that is part of ${BUNDLE} other than by name ({ … })`);
      out[name] = code.replace(inside, `$1./${BUNDLE}$3`);
    }
    return out;
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const stale = [];
  const files = readdirSync(from).filter((name) => name.endsWith('.js') && !DEV_ONLY.includes(name));
  const sources = {};
  if (!check) {
    rmSync(to, { recursive: true, force: true });
    mkdirSync(to, { recursive: true });
  }
  for (const name of files) {
    const built = minified(readFileSync(join(from, name), 'utf8'), name);
    sources[name] = built;
    const target = join(to, name);
    if (check) {
      if (!existsSync(target) || readFileSync(target, 'utf8') !== built) stale.push(name);
    } else writeFileSync(target, built);
  }
  const bundled = bundle(sources);
  const bundledTo = join(root, 'dist/bundled');
  if (!check) {
    rmSync(bundledTo, { recursive: true, force: true });
    mkdirSync(bundledTo, { recursive: true });
  }
  for (const [name, built] of Object.entries(bundled)) {
    const target = join(bundledTo, name);
    if (check) {
      if (!existsSync(target) || readFileSync(target, 'utf8') !== built) stale.push(`../bundled/${name}`);
    } else writeFileSync(target, built);
  }
  const split = bundle(sources, 'base.js');
  const splitTo = join(root, 'dist/split');
  if (!check) {
    rmSync(splitTo, { recursive: true, force: true });
    mkdirSync(splitTo, { recursive: true });
  }
  for (const [name, built] of Object.entries(split)) {
    const target = join(splitTo, name);
    if (check) {
      if (!existsSync(target) || readFileSync(target, 'utf8') !== built) stale.push(`../split/${name}`);
    } else writeFileSync(target, built);
  }
  const graph = moduleGraph(sources, bundled, split);
  const graphFile = join(root, 'dist/modules.js');
  if (check) {
    if (!existsSync(graphFile) || readFileSync(graphFile, 'utf8') !== graph) stale.push('../modules.js');
  } else writeFileSync(graphFile, graph);
  if (check) {
    const extra = [
      ...(existsSync(to) ? readdirSync(to).filter((name) => !files.includes(name)) : []),
      ...(existsSync(bundledTo) ? readdirSync(bundledTo).filter((name) => !(name in bundled)).map((name) => `../bundled/${name}`) : []),
      ...(existsSync(splitTo) ? readdirSync(splitTo).filter((name) => !(name in split)).map((name) => `../split/${name}`) : []),
    ];
    if (stale.length || extra.length) {
      console.error(`dist/production is out of date (${[...stale, ...extra].join(', ')}): run npm run build:production in runtime/`);
      process.exit(1);
    }
  }
}
