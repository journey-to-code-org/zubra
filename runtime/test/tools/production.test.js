import { test } from 'node:test';
import assert from 'node:assert/strict';
import { execFileSync, spawnSync } from 'node:child_process';
import { readFileSync, readdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { production, bundle, BUNDLE, PRIVATE } from '../../scripts/build-production.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '../..');

test('dist/production is up to date with src', () => {
  execFileSync(process.execPath, [join(root, 'scripts/build-production.js'), '--check'], { stdio: 'pipe' });
});

test('the production build has the same exports, and no hot reloading or DevTools hook', async () => {
  const [dev, prod] = await Promise.all([import('../../src/index.js'), import('../../dist/production/index.js')]);
  assert.deepEqual(Object.keys(prod).sort(), Object.keys(dev).sort());
  for (const name of ['element.js', 'effect.js', 'deep.js']) {
    const code = readFileSync(join(root, 'dist/production', name), 'utf8');
    for (const gone of ['__ZUBRA_HOT__', '#reload', 'zubra.hot', '@hot', '@dev', 'devhook.js', 'devtools.js', '__ZUBRA_DEVTOOLS__']) {
      assert.ok(!code.includes(gone), `${name}: ${gone}`);
    }
  }
});

test('the production build is minified, under a header pointing back to its source', () => {
  for (const name of ['element.js', 'effect.js', 'index.js']) {
    const [header, ...rest] = readFileSync(join(root, 'dist/production', name), 'utf8').split('\n');
    assert.match(header, new RegExp(`^// Generated by scripts/build-production\\.js from src/${name.replace('.', '\\.')}: .* Minified; read src/ instead\\. Do not edit\\.$`));
    const code = rest.join('\n');
    assert.ok(!/^\s*\/\//m.test(code) && !code.includes('/*'), `${name}: no comments`);
    assert.ok(rest.length <= 3, `${name}: ${rest.length} lines`);
  }
});

test('@hot and @dev fences', () => {
  const header = '// Generated by scripts/build-production.js from src/module: the runtime without hot reloading or the DevTools hook. Do not edit.\n';
  assert.equal(production('a\n// @hot\nb\n// @hot-end\nc'), `${header}a\nc`);
  assert.equal(production('a\n// @dev\nb\n// @dev-end\nc'), `${header}a\nc`);
  assert.throws(() => production('a\n// @hot\nb'), /without its end/);
  assert.throws(() => production('a\n// @dev\nb'), /without its end/);
  assert.throws(() => production('// @hot-end'), /@hot-end without its start/);
  assert.throws(() => production('// @dev-end'), /@dev-end without its start/);
});

test('dist/bundled: the entry and what it imports are one module, and every other module shares it', async () => {
  const dir = join(root, 'dist/bundled');
  const [prod, core, one, entry] = await Promise.all([import('../../dist/production/index.js'), import('../../dist/production/core.js'), import('../../dist/bundled/zubra.js'), import('../../dist/bundled/index.js')]);
  // zubra.js imports nothing, statically: it is the whole of the core's graph.
  assert.doesNotMatch(readFileSync(join(dir, BUNDLE), 'utf8'), /(?:\bfrom|\bimport)\s*["']/);
  // The core's exports, and what the other modules take from inside (an effect's root).
  assert.deepEqual(Object.keys(entry).sort(), Object.keys(prod).sort());
  for (const name of Object.keys(core)) assert.equal(entry[name], one[name], name);
  // zb-if's, zb-each's, event modifiers' and form controls' binders are the core's (a server from
  // before the split maps their entries to it; dist/split is what a current one sends);
  // zb-await's, the slots' and $define are files of their own, which a page loads if it uses them.
  for (const name of ['$when', '$each', '$modified', '$form']) assert.equal(one[name], entry[name], name);
  for (const [name, file] of [['$define', 'legacy.js'], ['$await', 'await.js'], ['$slot', 'slots.js'], ['$slotted', 'slots.js']]) {
    assert.equal(one[name], undefined, `${name} isn't in ${BUNDLE}`);
    assert.equal(typeof entry[name], name === '$slotted' ? 'object' : 'function', name);
    assert.equal(entry[name], (await import(`../../dist/bundled/${file}`))[name], name);
  }
  for (const name of ['root', 'batch', 'wrap']) assert.equal(typeof one[name], 'function', name);
  // The modules that went in are still there by name, and give the same things: one signal
  // graph, whichever file a module (or @zubra/sync) imports from.
  const [signal, effect, element, track] = await Promise.all(['signal.js', 'effect.js', 'element.js', 'track.js'].map((name) => import(`../../dist/bundled/${name}`)));
  assert.equal(signal.Signal, one.Signal);
  assert.equal(effect.effect, one.effect);
  assert.equal(effect.root, one.root);
  assert.equal(element.define, one.define);
  for (const name of ['spread.js', 'track.js', 'bridge.js', 'context-element.js', 'zag.js', 'each.js', 'slots.js', 'legacy.js']) {
    const code = readFileSync(join(dir, name), 'utf8');
    assert.match(code, /from"\.\/zubra\.js"/, name);
    assert.doesNotMatch(code, /from"\.\/(?:signal|effect|element|deep|resource|index|core|signal-impl)\.js"/, name);
  }
  // And it runs: an effect from one file sees a signal from another.
  const count = new signal.Signal.State(1);
  const seen = [];
  const stop = effect.effect(() => seen.push(count.get()));
  count.set(2);
  one.flush();
  assert.deepEqual(seen, [1, 2]);
  stop();
  assert.equal(Object.keys(track).length, 1);
});

test('dist/split: the base is one module, what only some components use is beside it, and core.js is the whole', async () => {
  const dir = join(root, 'dist/split');
  const [whole, base, core, index, lists] = await Promise.all([import('../../dist/bundled/zubra.js'), import('../../dist/split/zubra.js'), import('../../dist/split/core.js'), import('../../dist/split/index.js'), import('../../dist/modules.js')]);
  const { split } = lists;
  assert.doesNotMatch(readFileSync(join(dir, BUNDLE), 'utf8'), /(?:\bfrom|\bimport)\s*["']/, 'the base imports nothing');
  // The same script API as before the split, and as dist/bundled's: nothing gone, nothing new.
  assert.deepEqual(Object.keys(core).sort(), Object.keys(await import('../../dist/production/core.js')).sort());
  assert.deepEqual(Object.keys(index).sort(), Object.keys(await import('../../dist/production/index.js')).sort());
  // Each split name is in the file the list says, not in the base, and core.js's is that one.
  assert.equal(split.base, 'base.js');
  assert.deepEqual([...new Set(Object.values(split.names))].sort(), ['form.js', 'modifiers.js', 'provide.js', 'resource.js', 'shadow.js']);
  for (const [name, file] of Object.entries(split.names)) {
    assert.equal(base[name], undefined, `${name} isn't in the base`);
    const own = (await import(`../../dist/split/${file}`))[name];
    assert.ok(own !== undefined, `${name} is in ${file}`);
    assert.equal(core[name], own, name);
    assert.equal(typeof whole[name], typeof own, `${name}: dist/bundled's zubra.js still has it, for a server from before the split`);
  }
  // Everything else the core has is the base's own: one copy, whichever file a module asks.
  for (const name of Object.keys(core)) if (!split.names[name]) assert.equal(core[name], base[name], name);
  for (const file of new Set(Object.values(split.names))) {
    const code = readFileSync(join(dir, file), 'utf8');
    assert.match(code, /from"\.\/zubra\.js"/, file);
    assert.doesNotMatch(code, /from"\.\/(?:signal|effect|element|base|core)\.js"/, file);
  }
  // The list a server preloads from says the same.
  assert.deepEqual(split.modules['form.js'], ['zubra.js']);
  assert.deepEqual(split.modules['zubra.js'], []);
  assert.deepEqual(split.modules['core.js'].sort(), ['form.js', 'modifiers.js', 'provide.js', 'resource.js', 'shadow.js', 'zubra.js']);
});

test('bundle(): a name is given only by the module it belongs to, and a module that takes another is refused', () => {
  const sources = {
    'index.js': 'import{a as x}from"./one.js";import{pick as y}from"./pick.js";export{x as a,y as pick};',
    'one.js': 'export const a=1;export const inner=2;',
    'pick.js': 'import{pick as p}from"./impl.js";export const pick=globalThis.pick??p;',
    'impl.js': 'export const pick=3;',
    'other.js': 'import{inner as i}from"./one.js";export const b=i;',
    'lone.js': 'export const c=4;',
  };
  const out = bundle(sources, 'index.js');
  assert.deepEqual(Object.keys(out).sort(), ['index.js', 'lone.js', 'one.js', 'other.js', 'pick.js', BUNDLE].sort(), 'impl.js has nothing of its own to give');
  assert.match(out['one.js'], /export\{a,inner\}from"\.\/zubra\.js"/);
  assert.match(out['pick.js'], /export\{pick\}from"\.\/zubra\.js"/);
  assert.equal(out['other.js'], 'import{inner as i}from"./zubra.js";export const b=i;');
  assert.equal(out['lone.js'], sources['lone.js'], 'a module outside the graph is as it was');
  assert.throws(() => bundle({ ...sources, 'other.js': 'import{pick as p}from"./impl.js";export const b=p;' }, 'index.js'), /other\.js imports pick from impl\.js/);
  assert.throws(() => bundle({ ...sources, 'other.js': 'import*as all from"./one.js";export const b=all.a;' }, 'index.js'), /other than by name/);
});

// The production build gives private fields short names (`PRIVATE` in build-production.js), which
// is only right while each name is used on its module's own objects and nowhere else. Two checks:
// the unit tests, the 5,000-seed comparison with signal-polyfill among them, pass on the build
// itself; and none of the names is something the typings promise.
test('the unit tests pass on dist/production, where private fields have short names', () => {
  const run = spawnSync(process.execPath, ['--import', pathToFileURL(join(root, 'test/tools/on-production/register.mjs')).href, '--test', '--test-reporter=tap', ...readdirSync(join(root, 'test')).filter((name) => name.endsWith('.test.js')).map((name) => join(root, 'test', name))], { encoding: 'utf8', env: { ...process.env, NODE_TEST_CONTEXT: undefined } });
  const count = (what) => Number(run.stdout.match(new RegExp(`^# ${what} (\\d+)`, 'm'))?.[1]);
  assert.equal(count('fail'), 0, run.stdout.split('\n').filter((line) => line.startsWith('not ok')).join('\n'));
  assert.ok(count('pass') > 400, `only ${count('pass')} tests ran`);
  // And they did run on the build: its signal graph has no field by its source's name.
  const impl = readFileSync(join(root, 'dist/production/signal-impl.js'), 'utf8');
  for (const name of PRIVATE['signal-impl.js']) assert.ok(!new RegExp(`\\.${name}\\b`).test(impl), `signal-impl.js still has .${name}`);
});

test('no private field is a name the typings give', () => {
  // An effect's owner is handed out (`scope()`), so its public fields keep their names. The signal
  // graph's nodes never leave signal-impl.js: what's public there is the class around each.
  const declared = readFileSync(join(root, 'types/effect.d.ts'), 'utf8');
  for (const name of PRIVATE['effect.js']) assert.ok(!new RegExp(`\\b${name}\\??\\s*[:(]`).test(declared), `effect.js: ${name} is in types/effect.d.ts`);
});
